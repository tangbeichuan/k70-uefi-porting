#!/usr/bin/env python3
"""mk165.py -- generate _tools/patch_usb165.py from _tools/patch_usb164.py.

keys165 = keys164 (EP0 gadget + raw event trace + clear screen + halt) plus:
  * after EP0 resources are configured and the core runs, force a *fresh* host
    enumeration: clear DCTL.RUN_STOP (D+ pull-up off) -> 150 ms -> set it again
    (pull-up on) -> 150 ms; this is the software equivalent of
    dwc3_gadget_pullup(0 -> 1). With RUN_STOP=0 the core stops driving D+ so the
    host sees a disconnect and, on reconnect, starts a brand new enumeration
    (connect done + USB reset + SETUP), which is exactly what is missing now.
  * print "[165] replug: pull-up off/on" + a summary line so the serial/photo
    proves the path ran;
  * re-issue the EP0 configuration if DALEPENA lost its enable bits across the
    stop/start (defensive, only when the readback differs);
  * event window 8 s -> 20 s (enumeration may need a retry), then done+halt.
"""
import pathlib

SRC = pathlib.Path("/mnt/d/本地项目-01/_tools/patch_usb164.py")
DST = pathlib.Path("/mnt/d/本地项目-01/_tools/patch_usb165.py")

s = SRC.read_text(encoding="utf-8")
s = s.replace("164", "165")

# docstring header: the generator text mentions patch_usb164 -> already renamed
s = s.replace('"""patch_usb165.py -- keys165: EP0 gadget + screen clear + raw event trace + halt.',
              '"""patch_usb165.py -- keys165: EP0 + pull-up replug + raw event trace + halt.')

# ---- insert the replug sequence right before the SETUP arm --------------------
anchor = "  mUsb165State = USB165_ST_SETUP;\n  Usb165ArmSetup ();\n"
assert s.count(anchor) == 1, "arm anchor"
REPLUG = r'''  //
  // 5b) keys165: force a *fresh* host enumeration.  Clearing DCTL.RUN_STOP stops
  //     the device controller from driving the D+ pull-up, i.e. the host sees an
  //     electrical disconnect; setting it again is a reconnect.  This is the
  //     software equivalent of Linux dwc3_gadget_pullup(0 -> 1) and makes the
  //     host restart enumeration (connect done + USB reset + SETUP), which is
  //     what never happens if the host already gave up before our EP0 was armed.
  //
  Usb165Print (L"  [165] replug: pull-up off (DCTL.RUN_STOP=0)");
  Usb165Wr (USB165_DCTL, Usb165Rd (USB165_DCTL) & ~USB165_DCTL_RUN_STOP);
  gBS->Stall (150000);
  Usb165Print (L"  [165] replug: pull-up on (DCTL.RUN_STOP=1)");
  Usb165Wr (USB165_DCTL, Usb165Rd (USB165_DCTL) | USB165_DCTL_RUN_STOP);
  gBS->Stall (150000);
  for (I = 0; I < 200; I++) {
    if ((Usb165Rd (USB165_DSTS) & USB165_DSTS_DEVCTRLHLT) == 0) {
      break;
    }
    gBS->Stall (1000);
  }
  //
  // 5c) The stop/start may have dropped the endpoint resources: re-issue the
  //     EP0 configuration if DALEPENA no longer shows both endpoints enabled.
  //
  if ((Usb165Rd (USB165_DALEPENA) & 0x3) != 0x3) {
    Usb165Print (L"  [165] ep cfg redo after replug");
    Usb165EpCmd (0, USB165_DEPCMD_DEPSTARTCFG, 0, 0, 0);
    Usb165EpCmd (0, USB165_DEPCMD_SETEPCONFIG, (0U << 1) | (512U << 3),
                 (1U << 8) | (1U << 10) | (0U << 25), 0);
    Usb165EpCmd (0, USB165_DEPCMD_SETTRANSFRESOURCE, 1, 0, 0);
    Usb165EpCmd (1, USB165_DEPCMD_SETEPCONFIG, (0U << 1) | (512U << 3),
                 (1U << 8) | (1U << 10) | (1U << 25), 0);
    Usb165EpCmd (1, USB165_DEPCMD_SETTRANSFRESOURCE, 1, 0, 0);
    Usb165Wr (USB165_DALEPENA, 0x3);
  }
  Usb165Print (L"  [165] replug done: hlt22=%d DSTS=%08x DALEPENA=%08x",
               (Usb165Rd (USB165_DSTS) >> 22) & 1, Usb165Rd (USB165_DSTS),
               Usb165Rd (USB165_DALEPENA));
'''
s = s.replace(anchor, REPLUG + anchor, 1)

# ---- event window 8 s -> 20 s ------------------------------------------------
assert s.count("if (mTicks165 >= 8000) {") == 1, "window anchor"
s = s.replace("if (mTicks165 >= 8000) {", "if (mTicks165 >= 20000) {", 1)

# ---- docstring / footer ------------------------------------------------------
s = s.replace("Generated by mk164.py from patch_usb161.py.",
              "Generated by mk165.py from patch_usb164.py (keys161 EP0 + keys164 tracing).")
s = s.replace("print(\"PATCH_USB165 OK\")", "print(\"PATCH_USB165 OK\")")
s = s.replace('print("patch_usb165: Menu -> minimal DWC3 EP0 gadget (polled events, 1 cfg, no CDC/MSD)")',
              'print("patch_usb165: Menu -> DWC3 EP0 gadget + pull-up replug + raw event trace")')

# sanity: require the replug path is present
old_need = 'for need in ("[MENU165]", "Usb165Init", "Usb165Poll", "Usb165Stat", "Usb165Clear",'
assert s.count(old_need) == 1, "need anchor"
s = s.replace(old_need,
              'for need in ("[MENU165]", "Usb165Init", "Usb165Poll", "Usb165Stat", "Usb165Clear",\n'
              '             "[165] replug: pull-up off", "[165] replug: pull-up on", "replug done",',
              1)

# the arm anchor also appears in the sanity "for bad" list? no. ensure marker list fine.
DST.write_text(s, encoding="utf-8")
print(f"wrote {DST} ({len(s)} bytes)")
for probe in ("[165] replug: pull-up off", "[165] replug: pull-up on", "replug done",
              "mTicks165 >= 20000", "mUsb165Events >= 16", "Usb165ArmSetup ()", "CpuDeadLoop ()"):
    print(f"  contains {probe!r}: {probe in s}")
