#!/usr/bin/env bash
set -u
A=/tmp/ucfg_vt.asm
dump() { echo "===== $1 ====="; awk -v lo="$2" -v hi="$3" '
  /^[[:space:]]+[0-9a-f]+:/ {
    a = $1; sub(":","",a); v = strtonum("0x" a);
    if (v >= lo && v <= hi) print
  }' "$A"; }
dump "iface methods 0x1460-0x1560" 0x1460 0x1560
dump "iface methods 0x1560-0x1660" 0x1560 0x1660
dump "iface+0x80 method 0x169c-0x1714" 0x169c 0x1714
dump "iface+0x98..0xb0 thunks 0x1714-0x1740" 0x1714 0x1740
dump "DWC3 struct builder 0x8850-0x88a0" 0x8850 0x88a0
dump "GCTL reader 0x8d80-0x8e50" 0x8d80 0x8e50
dump "role/status 0xa140-0xa200" 0xa140 0xa200
dump "DSTS/GCTL user 0xa380-0xa4e0" 0xa380 0xa4e0
