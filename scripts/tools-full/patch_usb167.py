#define USB167_SMMU_GR0_S2CR(n) (0xC00 + ((n) * 4))
#define USB167_SMMU_SMR_VALID   0x80000000U
#define USB167_S2CR_TYPE_BYPASS (1U << 16)   // ARM SMMU-500 S2CR.TYPE: 0=trans, 1=bypass, 2=fault

